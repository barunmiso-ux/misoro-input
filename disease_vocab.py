"""초진 명단 '진료과목'(R열) 표기를 그 탭 집계표(Q159:Q186) 이름으로 맞춘다.

왜(2026-10-13): 월간·주간탭의 질환 집계(D169 피부 = R164:R172 합, D170 호흡기 = R159:R163 합)는
집계표에 적힌 이름과 **정확히 같은** 값만 센다(COUNTIF). OK차트 VIP 칸에 '알레르기비염'·
'지루성두피'·'통증증' 처럼 적히면 집계에서 빠져, 평택 9월 호흡기가 14명인데 2명으로,
특화 신환이 17명으로 잡혀 한약 결제율이 부풀었다.

규칙: 탭 집계표에 이미 있는 이름은 그대로. 없으면 아래 후보를 순서대로 보고 **그 탭 표에
있는 첫 이름**으로 바꾼다. 후보가 하나도 표에 없거나 모르는 이름이면 그대로 둔다(추측 안 함).
집계표 이름은 지점마다 조금 다르다(대전 '알레르기비염' / 평택 '알레르기비염(첩약보험)').
"""
from __future__ import annotations

# 변형·오타 → 후보(앞이 우선). 표에 없는 질환은 같은 질환군의 '기타…' 로 보낸다.
CANDIDATES = {
    "알레르기비염": ["알레르기비염", "비염"],
    "알레르기비염(첩약보험_": ["알레르기비염(첩약보험)", "알레르기비염", "비염"],
    "알레르기비염(첩약보험)": ["알레르기비염(첩약보험)", "알레르기비염", "비염"],
    "지루성두피": ["지루성피부염"], "지루성두피염": ["지루성피부염"], "지루피부염": ["지루성피부염"],
    "비염 염": ["비염"],
    "피부염": ["기타피부"], "여드름": ["기타피부"], "모낭염": ["기타피부"], "백반증": ["기타피부"],
    "장미색비강진": ["기타피부"],
    "통증증": ["통증"], "보약약": ["보약"], "성장": ["성장질환"],
    "안면신경마비": ["안면신경마비(첩약보험)", "기타"],
    "생리통": ["생리통(첩약보험)", "기타"],
    "뇌혈관질환후유증": ["뇌혈관질환후유증(첩약보험)", "기타"],
    # 첩약보험 여부를 알 수 없는 표기 — 보험 항목으로 단정하지 않고 '기타'
    "월경통": ["기타"], "중풍후유증": ["기타"],
    "기능성소화불량": ["기타"], "요추추간판탈출증": ["기타"],
    "일반치료": ["기타"],
}

VOCAB_RANGE = "Q159:Q186"


def normalize(value: str, vocab: set) -> str:
    """vocab(그 탭 집계표 이름들)에 맞춘 표기. 바꿀 근거가 없으면 원래 값."""
    x = str(value or "").strip()
    if not x or not vocab or x in vocab:
        return x
    for c in CANDIDATES.get(x, []):
        if c in vocab:
            return c
    return x


def tab_vocab(sh, sid: str, tab: str) -> set:
    """탭의 집계표 이름 집합. 표가 없으면(빈 집합) 정규화하지 않는다."""
    try:
        v = sh.values().get(spreadsheetId=sid, range=f"'{tab}'!{VOCAB_RANGE}").execute().get("values", [])
    except Exception:
        return set()
    names = {str(r[0]).strip() for r in v if r and str(r[0]).strip()}
    return names if len(names) >= 20 else set()
